// 章（物語・敵の言葉・難しさ）。React にも three.js にも依存しない。
//
// 言葉は { text: 画面に大きく出す字, kana: 読み（ローマ字の判定に使う） }。
// kana に表に無い文字（漢字など）を入れるとテストで落ちる（romaji.test.ts）。
//
// 章を足すときは CHAPTERS に足し、scene/themes.ts に同じ id の色を足す。

export interface Word {
  text: string
  kana: string
}

export interface StoryLine {
  /** 話している人（無ければ地の文） */
  who?: string
  text: string
}

export interface Wave {
  /** この波で出る影の数 */
  count: number
  /** 次の影が出るまでの秒数 */
  interval: number
  /** 同時にいてよい影の数 */
  maxAlive: number
}

export interface BossDef {
  name: string
  /** ボスがなくした言葉。順番に打って返す */
  phrases: Word[]
  /** 子分の影を呼ぶ間隔（秒）。0 なら呼ばない */
  summonEvery: number
}

export interface Chapter {
  id: string
  /** 「第一章」など */
  number: string
  title: string
  /** 章選びに出す一行 */
  blurb: string
  intro: StoryLine[]
  outro: StoryLine[]
  words: Word[]
  waves: Wave[]
  boss: BossDef | null
  /** 影が出てから目の前に来るまでの秒数 = base + perChar × ローマ字の長さ */
  baseTime: number
  perChar: number
  /** 霧: 影がこの距離（m）より近づくまで言葉が見えない。0 なら最初から見える */
  reveal: number
  /** 速い狐火が混ざる割合（0〜1） */
  fastChance: number
  /** 影が左右に揺れる大きさ（m） */
  sway: number
}

