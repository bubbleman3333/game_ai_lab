// 章（物語・敵の言葉・難しさ）。React にも three.js にも依存しない。
//
// 物語の骨組み（2 本の筋）:
//   1. 夜明けまでに、影にさらわれた妹ミオを連れ戻す（遊ぶ人の目的。おばあが最初に「やることは三つ」と言う）
//   2. 十年前に森で消えた母さん（先代の灯守サヨ）に何があったのか。渡されたランタンは母さんの形見
//   章ごとに「影に捕らわれた誰か」をボスから助け出し、助けた者が仲間になって力をくれる（Ally）。
//   助けた者が、母さんのこと・森のこと・影の正体を少しずつ教えてくれる。
//   結末: 影はみな、名前を忘れられた森（夜の主）から生まれていた。母さんは十年間その中で灯をともし、
//   村が呑まれないよう食い止めていた。森の名前を取り戻すと、ミオと母さんを連れて朝の村へ帰る。
//
// 戦いの最中にも物語が進む: 波の始まり（waveLines）と半ば（midLines）の声、ボスの登場（appear）、
// ボスが言葉を返されるたびに漏らす本音（reactions）。金色の影が「母の手記」（journal.ts）を持っている。
//
// 言葉は { text: 画面に大きく出す字, kana: 読み（ローマ字の判定に使う） }。
// kana に表に無い文字（漢字など）を入れるとテストで落ちる（typing.test.ts）。
//
// 章を足すときは CHAPTERS に足し、scene/themes.ts に同じ id の色を足す。

export interface Word {
  text: string
  kana: string
}

/** 物語の効果音（sounds.ts の storySfx） */
export type Sfx =
  | 'higurashi' | 'door' | 'heartbeat' | 'gust' | 'footsteps' | 'owl' | 'ignite'
  | 'whisper' | 'rumble' | 'splash' | 'bell' | 'flutter'

export interface StoryLine {
  /** 話している人（無ければ地の文） */
  who?: string
  text: string
  /**
   * 'reward' は仲間になった・力を得たときの特別な表示。
   * 'scene' は場面の見出し（「― その夜 ―」など。真ん中に大きく出す）。
   * 'recap' はこれまでのあらすじ（章の最初に出す）。
   * 'voice' は影や森の不気味な声（文字が震える）。
   * 'goal' は目的（大きな札で出す。何をすればいいのかを、はっきり見せる）。
   */
  kind?: 'reward' | 'scene' | 'recap' | 'voice' | 'goal'
  /** この行が出た瞬間に鳴らす効果音 */
  sfx?: Sfx
  /** 画面の演出: 揺れる / 白く光る / 暗くなる */
  fx?: 'shake' | 'flash' | 'dark'
  /** ここから背景を切り替える（scene/themes.ts の id）。書かなければ前の行の背景のまま。最初は章の森 */
  bg?: string
}

export interface Wave {
  /** この波で出る影の数 */
  count: number
  /** 次の影が出るまでの秒数 */
  interval: number
  /** 同時にいてよい影の数 */
  maxAlive: number
}

/**
 * ボスの攻撃（game.ts）。どれも力を溜めて（boss-charge）から放つ。
 *   orbs 火の玉を 3 つ投げる / rain 火の雨（空から 5 つ降ってくる）/ howl 咆哮（打ちかけが崩れ、お手本が消える）
 *   ink 闇を吐く / eclipse 日蝕（長い闇）/ quake 地鳴り（影がみな近づく）/ summon 子分を呼ぶ
 *   hands 足もとから手が生える / phantoms 幻影（3 体のうち 1 体だけ本物）/ bombs 時限の影を 2 体
 *   flank 左右から回り込ませる / rush 3 体が同時に溜めて飛びかかる
 */
export type BossAttack =
  | 'orbs' | 'rain' | 'howl' | 'ink' | 'eclipse' | 'quake' | 'summon'
  | 'hands' | 'phantoms' | 'bombs' | 'flank' | 'rush'

/**
 * 陣形（game.ts）。1 体ずつではなく、まとまって仕掛けてくる。
 *   surround 包囲（5 体が弧を描いて同時に迫る）/ column 行列（小さな影が一列で次々）/ pincer 挟み撃ち（左右から回り込む）
 *   rain 火の雨（空から火の玉）/ rush 一斉突撃（3 体が同時に溜めて飛びかかる）/ hands 地の手（足もとから 3 本）
 */
export type Formation = 'surround' | 'column' | 'pincer' | 'rain' | 'rush' | 'hands'

export interface BossDef {
  name: string
  /** ボスが現れたときのひとこと */
  appear: StoryLine
  /** ボスがなくした言葉。順番に打って返す */
  phrases: Word[]
  /** 言葉を 1 つ返すたびにボスが漏らす本音（phrases と同じ数。最後は倒したとき） */
  reactions: string[]
  /** 使う攻撃（順番に使う） */
  attacks: BossAttack[]
  /** 何秒ごとに攻撃するか（言葉を半分返すと怒って、間隔が短くなる） */
  attackEvery: number
  /** 言葉を半分返して怒ったときのひとこと */
  enrage: StoryLine
}

/** 助け出すと仲間になり、戦いで力を貸してくれる者 */
export type AllyId = 'kuro' | 'ruri' | 'bell' | 'mio'

export interface Ally {
  id: AllyId
  name: string
  /** 何をしてくれるか（拠点・仲間になったときに出す） */
  power: string
}

