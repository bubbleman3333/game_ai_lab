/**
 * 影の動き方（game.ts）。
 *   walk まっすぐ / creep じわじわ加速 / hop 跳ねては止まる / lunge 途中で溜めて、いきなり飛びかかる
 *   blink 消えては近くに現れる / zigzag 大きく蛇行 / ambush いきなり目の前の茂みから出る
 *   tank 言葉を 2 つ打たないと倒れない / split 倒すと小さな影 2 体に分かれる（mini）
 */
export type Behavior = 'walk' | 'creep' | 'hop' | 'lunge' | 'blink' | 'zigzag' | 'ambush' | 'tank' | 'split' | 'mini'

export interface Chapter {
  id: string
  /** 「第一章」など */
  number: string
  title: string
  /** 章選びに出す一行 */
  blurb: string
  /** 物語の中の時刻（夜明けまでの残り） */
  hour: string
  /** この章の目的（物語の見出しと戦いの画面に出す） */
  goal: string
  /** この章で助け出す仲間（無ければ null） */
  rescue: AllyId | null
  intro: StoryLine[]
  outro: StoryLine[]
  /** 波が始まるときの声（waves と同じ数） */
  waveLines: StoryLine[]
  words: Word[]
  waves: Wave[]
  boss: BossDef | null
  /** 影が出てから目の前に来るまでの秒数 = base + perChar × ローマ字の長さ */
  baseTime: number
  perChar: number
  /** 霧: 影がこの距離（m）より近づくまで言葉が見えない。0 なら最初から見える */
  reveal: number
  /** 速い狐火が混ざる割合（0〜1） */
  fastChance: number
  /** 影が左右に揺れる大きさ（m） */
  sway: number
  /** どの動きの影が、どれくらいの割合で出るか（重み）。章が進むほど種類が増える */
  behaviors: Partial<Record<Behavior, number>>
}

